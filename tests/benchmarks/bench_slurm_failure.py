# tests/benchmarks/bench_slurm_failure.py
#
# JASMIN test for the SLURM executor's failure propagation (todos.md
# "Smaller debts": "Check that failed SLURM jobs cause dependent jobs to not
# run"; slurm_implementation.md "Scheduler quirks": aftercorr semantics with
# partially-failed upstream arrays).
#
# bench_slurm_pipeline.py is the happy-path twin: a clean stage1 -> stage2
# wide array that confirms the sidecar/ingest path has no DB-lock livelock.
# This script instead makes a *subset* of stage1 deliberately fail, and
# checks that the SLURM dependency wiring stops exactly the corresponding
# stage2 elements -- and only those -- from ever running.
#
# Why element-wise matters. stage2 shares stage1's matrix 1-to-1, so the
# executor wires it as `--dependency=aftercorr:<stage1_array>` (slurm_executor
# ._dependency): element N of stage2 waits on element N of stage1, not on the
# whole upstream array. So a failure in stage1[i] must:
#   - block stage2[i] (it never launches; SLURM either cancels it or parks it
#     PD with reason DependencyNeverSatisfied), while
#   - leaving every stage2[j] with a successful stage1[j] free to run.
#
# The bug this guards against (todos.md "Failure UX"): downstream tasks of a
# failed task running anyway and failing "naturally" on the missing input.
# That would show up here as stage2 *failed* > 0. The correct outcome is
# stage2 failed == 0 and the blocked elements left *pending* (no sidecar,
# unrecorded), so fixing the upstream lets a later run pick them up.
#
# stage1 fails when (i % fail_every == 0), so index 0 always fails and there
# is always a healthy mix of pass/fail elements. Failure is a raise inside
# the task; `remake run-array-task` records it as a failure sidecar (status
# failed + traceback), exercising the failure-recording path too.
#
# Usage on JASMIN (run from anywhere; --dir is a scratch working dir):
#
#   # 1. Generate the scratch dir + pipeline (pick an account you belong to).
#   uv run python tests/benchmarks/bench_slurm_failure.py setup \
#       --dir /work/scratch-pw3/$USER/slurm_failure_40 \
#       --n 40 --fail-every 4 --account afesp
#
#   # 2. Submit the pipeline via the SLURM executor.
#   uv run python tests/benchmarks/bench_slurm_failure.py submit \
#       --dir /work/scratch-pw3/$USER/slurm_failure_40
#
#   # 3. Once stage1 has finished and stage2 has settled (some elements may sit
#   #    PD with reason DependencyNeverSatisfied -- that is a pass, not a hang),
#   #    ingest sidecars and check propagation. Add --cancel-blocked to scancel
#   #    any stage2 elements SLURM parked instead of cancelling.
#   uv run python tests/benchmarks/bench_slurm_failure.py report \
#       --dir /work/scratch-pw3/$USER/slurm_failure_40
#
# Not collected by pytest (no test_ prefix); run manually.

import argparse
import json
import os
import subprocess as sp
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]

# A two-rule pipeline where stage1 fails on a subset of its matrix. stage2
# shares stage1's matrix 1-to-1 and depends on it, so the executor wires an
# aftercorr array dependency -- the case under test. Parameters come from a
# sibling bench_params.yaml so the {i} matrix placeholders never collide with
# str.format brace-escaping.
REMAKEFILE = '''\
# Generated by bench_slurm_failure.py -- partial-failure wide-array pipeline.
from pathlib import Path

import yaml

from remake import Remake, rule

P = yaml.safe_load(Path('bench_params.yaml').read_text())
N = P['n']
FAIL_EVERY = P['fail_every']

rmk = Remake(config={'slurm': {
    'account':        P['account'],
    'partition':      P['partition'],
    'qos':            P['qos'],
    'time':           P['time'],
    'mem':            P['mem'],
    'array_throttle': P['array_throttle'],
}})

MATRIX = [{'i': i} for i in range(N)]


@rule(
    outputs = {'out': 'data/stage1/{i}.txt'},
    matrix  = MATRIX,
    uses    = {'FAIL_EVERY': FAIL_EVERY},
)
def stage1(outputs, i):
    from pathlib import Path
    # Deliberate, deterministic failure on a subset. The output is NOT written
    # in the failing branch, so a stage2 element that wrongly ran would fail on
    # the missing input -- exactly the symptom we are testing is absent.
    if FAIL_EVERY and i % FAIL_EVERY == 0:
        raise RuntimeError(f'deliberate stage1 failure for i={i}')
    out = Path(outputs['out'])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(str(i))


@rule(
    inputs     = {'in': 'data/stage1/{i}.txt'},
    outputs    = {'out': 'data/stage2/{i}.txt'},
    matrix     = stage1.matrix,
    depends_on = [stage1],
)
def stage2(inputs, outputs, i):
    from pathlib import Path
    out = Path(outputs['out'])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(Path(inputs['in']).read_text())


rmk.rules_from_current_module()
'''

REMAKEFILE_NAME = 'bench_remake.py'
PARAMS_NAME = 'bench_params.yaml'


def _remake(dir_, *args):
    """Run the installed `remake` CLI inside the scratch dir (the SLURM
    executor and the DB are all cwd-relative)."""
    return sp.run(
        ['uv', 'run', '--project', str(REPO_ROOT), 'remake', *args],
        cwd=dir_, capture_output=True, text=True,
    )


def _failed_indices(n, fail_every):
    return [i for i in range(n) if fail_every and i % fail_every == 0]


def cmd_setup(args):
    dir_ = Path(args.dir)
    dir_.mkdir(parents=True, exist_ok=True)

    params = {
        'n': args.n,
        'fail_every': args.fail_every,
        'account': args.account,
        'partition': args.partition,
        'qos': args.qos,
        'time': args.time,
        'mem': args.mem,
        'array_throttle': args.array_throttle,
    }
    (dir_ / PARAMS_NAME).write_text(yaml.safe_dump(params, sort_keys=False))
    (dir_ / REMAKEFILE_NAME).write_text(REMAKEFILE)

    n_fail = len(_failed_indices(args.n, args.fail_every))
    print(f'Wrote {dir_ / REMAKEFILE_NAME} and {dir_ / PARAMS_NAME}')
    print(f'  n={args.n} (=> {2 * args.n} tasks across 2 array jobs), '
          f'fail_every={args.fail_every}, account={args.account}')
    print(f'  stage1 will fail on {n_fail} element(s): '
          f'{_failed_indices(args.n, args.fail_every)}')
    print(f'  => expect stage2 to block {n_fail} element(s), run '
          f'{args.n - n_fail}.')
    print(f'Next: {sys.argv[0]} submit --dir {dir_}')


def cmd_submit(args):
    dir_ = Path(args.dir)
    if not (dir_ / REMAKEFILE_NAME).exists():
        sys.exit(f'No {dir_ / REMAKEFILE_NAME} -- run `setup` first')

    print(f'Submitting {REMAKEFILE_NAME} via the SLURM executor from {dir_} ...')
    result = _remake(dir_, 'run', REMAKEFILE_NAME, '--executor', 'slurm')
    sys.stdout.write(result.stdout)
    sys.stderr.write(result.stderr)
    if result.returncode != 0:
        sys.exit(f'submit failed (exit {result.returncode})')
    print('\nSubmitted. Watch with `squeue -u $USER` or '
          f'`cd {dir_} && remake slurm-status {REMAKEFILE_NAME}`.')
    print('Some stage2 elements may sit PD (DependencyNeverSatisfied) until '
          'cancelled -- that is the expected blocked state, not a hang.')
    print(f'When stage1 is done: {sys.argv[0]} report --dir {dir_}')


def _blocked_stage2_elements(dir_):
    """squeue elements of the stage2 array still parked with an unsatisfiable
    dependency. Returns [(elem_id, state, reason)]. Empty when SLURM has
    already cancelled them (kill_invalid_depend) or squeue is unavailable."""
    sys.path.insert(0, str(REPO_ROOT / 'src'))
    from remake.executors.slurm_executor import SqueueError, squeue_snapshot

    sidecar = dir_ / '.remake' / 'jobs' / 'stage2.jobids.json'
    if not sidecar.exists():
        return []
    base = json.loads(sidecar.read_text()).get('slurm_array_job_id')
    try:
        snap = squeue_snapshot()
    except SqueueError:
        return []
    return [
        (elem, state, reason)
        for elem, state, reason in snap.get(str(base), [])
        if 'Dependency' in reason
    ]


def cmd_report(args):
    dir_ = Path(args.dir)
    params = yaml.safe_load((dir_ / PARAMS_NAME).read_text())
    n = params['n']
    fail_every = params['fail_every']
    failed = set(_failed_indices(n, fail_every))
    n_fail = len(failed)

    # Any stage2 elements SLURM parked rather than cancelled. Optionally
    # scancel them so the test cleans up after itself (and so a re-run isn't
    # blocked by stale queued jobs). Done before ingest so squeue reflects the
    # blocked state at report time.
    blocked = _blocked_stage2_elements(dir_)
    if blocked and args.cancel_blocked:
        ids = [elem for elem, _, _ in blocked]
        sp.run(['scancel', *ids], check=False)
        print(f'scancelled {len(ids)} parked stage2 element(s): {ids}\n')

    # `remake info` calls plan(), which ingests pending sidecars into the DB
    # before reading it. stage1 failure sidecars become failed; blocked stage2
    # elements have no sidecar, so they stay pending.
    result = _remake(dir_, 'info', REMAKEFILE_NAME, '--json')
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        sys.exit(f'`remake info` failed (exit {result.returncode})')
    info = json.loads(result.stdout)
    rules = {r['rule']: r for r in info['rules'] if not r.get('deferred')}

    print(f'=== bench_slurm_failure report ({dir_}) ===')
    print(f'n={n}  fail_every={fail_every}  '
          f'stage1 fails {n_fail} element(s): {sorted(failed)}\n')

    ok = True

    # (1) DB status counts: stage1 splits success/failed; stage2 runs the
    #     survivors and leaves the blocked ones pending (never failed).
    expect = {
        'stage1': {'up_to_date': n - n_fail, 'failed': n_fail, 'pending': 0},
        'stage2': {'up_to_date': n - n_fail, 'failed': 0,      'pending': n_fail},
    }
    print(f'{"rule":<8} {"up-to-date":>10} {"failed":>7} {"pending":>8}   '
          f'{"(expected up-to-date/failed/pending)"}')
    for name in ('stage1', 'stage2'):
        r = rules.get(name)
        if r is None:
            print(f'{name:<8} (not reported)')
            ok = False
            continue
        e = expect[name]
        got = (r['up_to_date'], r['failed'], r['pending'])
        want = (e['up_to_date'], e['failed'], e['pending'])
        flag = '' if got == want else '  <-- MISMATCH'
        if got != want:
            ok = False
        print(f'{name:<8} {r["up_to_date"]:>10} {r["failed"]:>7} {r["pending"]:>8}   '
              f'(expected {want[0]}/{want[1]}/{want[2]}){flag}')

    # (2) The core invariant, checked element-wise on the filesystem: a stage2
    #     output exists iff its stage1 succeeded. A blocked element that wrongly
    #     ran would either leave an output (ran on a stale/missing input) or
    #     have failed -- both caught here / above.
    print('\nElement-wise output check (stage2/{i}.txt exists iff stage1[i] ok):')
    wrong_present, wrong_absent = [], []
    for i in range(n):
        exists = (dir_ / 'data' / 'stage2' / f'{i}.txt').exists()
        should_exist = i not in failed
        if exists and not should_exist:
            wrong_present.append(i)
        elif not exists and should_exist:
            wrong_absent.append(i)
    if wrong_present:
        ok = False
        print(f'  FAIL: stage2 ran for blocked upstream-failed indices: '
              f'{wrong_present}')
    if wrong_absent:
        ok = False
        print(f'  FAIL: stage2 missing for indices whose stage1 succeeded: '
              f'{wrong_absent}')
    if not wrong_present and not wrong_absent:
        print(f'  OK: {n - n_fail} present, {n_fail} correctly absent.')

    # (3) Surface any still-parked stage2 elements (informational unless they
    #     should have run).
    print(f'\nstage2 elements parked on dependency in squeue: {len(blocked)}')
    for elem, state, reason in blocked[:20]:
        print(f'  {elem}  {state}  {reason}')
    if blocked and not args.cancel_blocked:
        print('  (re-run with --cancel-blocked to scancel these.)')

    print()
    if ok:
        print('PASS: failed stage1 elements blocked exactly their stage2 '
              'dependants; survivors ran; blocked tasks left pending.')
    else:
        print('FAIL: see mismatches above. If stage2 is still in flight, wait '
              'and re-run `report`; otherwise the dependency wiring let blocked '
              'tasks run (or recorded them wrong).')
        sys.exit(1)


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = parser.add_subparsers(dest='cmd', required=True)

    p_setup = sub.add_parser('setup', help='write scratch dir + pipeline')
    p_setup.add_argument('--dir', required=True)
    p_setup.add_argument('--n', type=int, default=40,
                         help='matrix size per rule (2*N tasks total)')
    p_setup.add_argument('--fail-every', type=int, default=4,
                         help='stage1 fails when i %% fail_every == 0 '
                              '(0 disables failures)')
    p_setup.add_argument('--account', default=os.environ.get('REMAKE_SLURM_ACCOUNT', 'afesp'))
    p_setup.add_argument('--partition', default='standard')
    p_setup.add_argument('--qos', default='standard')
    p_setup.add_argument('--time', default='00:40:00')
    p_setup.add_argument('--mem', default='256M')
    p_setup.add_argument('--array-throttle', type=int, default=10,
                         help='max concurrent array elements (--array=0-N%%T); '
                              'keeps 40 cold `import remake` calls from '
                              'storming one node into the wall-clock limit')
    p_setup.set_defaults(func=cmd_setup)

    p_submit = sub.add_parser('submit', help='submit the pipeline via SLURM')
    p_submit.add_argument('--dir', required=True)
    p_submit.set_defaults(func=cmd_submit)

    p_report = sub.add_parser('report', help='ingest sidecars + check propagation')
    p_report.add_argument('--dir', required=True)
    p_report.add_argument('--cancel-blocked', action='store_true',
                          help='scancel stage2 elements SLURM parked on a '
                               'never-satisfied dependency')
    p_report.set_defaults(func=cmd_report)

    args = parser.parse_args()
    args.func(args)


if __name__ == '__main__':
    main()
