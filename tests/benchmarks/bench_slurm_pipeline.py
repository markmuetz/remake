# tests/benchmarks/bench_slurm_pipeline.py
#
# JASMIN revalidation of the post-livelock SLURM stack through the *real
# pipeline path* (slurm_implementation.md §"Suggested order" item 4, second
# pass; implementation_plan.md "What's left" item 1).
#
# bench_sqlite_contention.py is the negative control: it drives raw
# Sqlite3Backend.update_task() from a wide array with no Remake/Executor in
# the loop, and reproduces the 400/800-way "database is locked" livelock that
# motivated the sidecar/ingest design. It deliberately exercises the OLD
# direct-write path, so it cannot confirm the fix.
#
# This script is the positive test: a genuine two-rule remake pipeline
# (stage1 -> stage2, same matrix, so stage2 gets an aftercorr array
# dependency) submitted as a wide SLURM array via `remake run --executor
# slurm`. Every array element goes through `remake run-array-task`, which
# opens NO DB connection at all -- results land in
# `.remake/tasks/results/.../*.json` sidecars and are batch-ingested by the
# next `remake` invocation that reads the DB. The benchmark confirms, at
# 400- and 800-way, that:
#   - no element ever hit "database is locked" (per-task logs + slurm stderr);
#   - all 2*N sidecars ingested cleanly (DB shows 2*N successes, 0 pending);
#   - no sidecars left orphaned.
#
# work_seconds defaults to 0: every element finishes near-simultaneously, the
# worst case for the old path (synchronised write burst) and the hardest case
# for sidecar-write + batched ingest.
#
# Usage on JASMIN (run from anywhere; --dir is a scratch working dir):
#
#   # 1. Generate the scratch dir + pipeline (pick an account you belong to).
#   uv run python tests/benchmarks/bench_slurm_pipeline.py setup \
#       --dir /work/scratch-pw3/$USER/slurm_pipeline_800 \
#       --n 800 --account afesp
#
#   # 2. Submit the real pipeline as SLURM array jobs.
#   uv run python tests/benchmarks/bench_slurm_pipeline.py submit \
#       --dir /work/scratch-pw3/$USER/slurm_pipeline_800
#
#   # 3. After both arrays finish (watch with: remake slurm-status, or squeue),
#   #    ingest sidecars and check for livelock / lost results.
#   uv run python tests/benchmarks/bench_slurm_pipeline.py report \
#       --dir /work/scratch-pw3/$USER/slurm_pipeline_800
#
# Run it twice (--n 400 and --n 800) for the two data points the design doc
# asks for. Not collected by pytest (no test_ prefix); run manually.

import argparse
import json
import os
import subprocess as sp
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]

# A self-contained two-rule pipeline. Reads its parameters from a sibling
# bench_params.yaml (human-readable config -> YAML; see remake3_design.md
# "Config file formats") so the {i} matrix placeholders never collide with
# str.format brace-escaping. stage1 has no inputs (pure generator); stage2
# shares stage1's matrix 1-to-1, so the executor wires it as an aftercorr
# array dependency -- the canonical wide-array shape.
REMAKEFILE = '''\
# Generated by bench_slurm_pipeline.py -- synthetic wide-array pipeline.
from pathlib import Path

import yaml

from remake import Remake, rule

P = yaml.safe_load(Path('bench_params.yaml').read_text())
N = P['n']
WORK = P['work_seconds']

rmk = Remake(config={'slurm': {
    'account':   P['account'],
    'partition': P['partition'],
    'qos':       P['qos'],
    'time':      P['time'],
    'mem':       P['mem'],
}})

MATRIX = [{'i': i} for i in range(N)]


@rule(
    outputs = {'out': 'data/stage1/{i}.txt'},
    matrix  = MATRIX,
    uses    = {'WORK': WORK},
)
def stage1(outputs, i):
    import time
    from pathlib import Path
    if WORK:
        time.sleep(WORK)
    out = Path(outputs['out'])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(str(i))


@rule(
    inputs     = {'in': 'data/stage1/{i}.txt'},
    outputs    = {'out': 'data/stage2/{i}.txt'},
    matrix     = stage1.matrix,
    depends_on = [stage1],
)
def stage2(inputs, outputs, i):
    from pathlib import Path
    out = Path(outputs['out'])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(Path(inputs['in']).read_text())


rmk.rules_from_current_module()
'''

REMAKEFILE_NAME = 'bench_remake.py'
PARAMS_NAME = 'bench_params.yaml'
LOCK_MARKERS = ('database is locked', 'OperationalError', 'database table is locked')


def _remake(dir_, *args):
    """Run the installed `remake` CLI inside the scratch dir (the SLURM
    executor and the DB are all cwd-relative)."""
    return sp.run(
        ['uv', 'run', '--project', str(REPO_ROOT), 'remake', *args],
        cwd=dir_, capture_output=True, text=True,
    )


def cmd_setup(args):
    dir_ = Path(args.dir)
    dir_.mkdir(parents=True, exist_ok=True)

    params = {
        'n': args.n,
        'work_seconds': args.work_seconds,
        'account': args.account,
        'partition': args.partition,
        'qos': args.qos,
        'time': args.time,
        'mem': args.mem,
    }
    (dir_ / PARAMS_NAME).write_text(yaml.safe_dump(params, sort_keys=False))
    (dir_ / REMAKEFILE_NAME).write_text(REMAKEFILE)

    print(f'Wrote {dir_ / REMAKEFILE_NAME} and {dir_ / PARAMS_NAME}')
    print(f'  n={args.n} (=> {2 * args.n} tasks across 2 array jobs), '
          f'work_seconds={args.work_seconds}, account={args.account}')
    print(f'Next: {sys.argv[0]} submit --dir {dir_}')


def cmd_submit(args):
    dir_ = Path(args.dir)
    if not (dir_ / REMAKEFILE_NAME).exists():
        sys.exit(f'No {dir_ / REMAKEFILE_NAME} -- run `setup` first')

    print(f'Submitting {REMAKEFILE_NAME} via the SLURM executor from {dir_} ...')
    result = _remake(dir_, 'run', REMAKEFILE_NAME, '--executor', 'slurm')
    sys.stdout.write(result.stdout)
    sys.stderr.write(result.stderr)
    if result.returncode != 0:
        sys.exit(f'submit failed (exit {result.returncode})')
    print('\nSubmitted. Watch with `squeue -u $USER` or '
          f'`cd {dir_} && remake slurm-status {REMAKEFILE_NAME}`.')
    print(f'When both arrays are done: {sys.argv[0]} report --dir {dir_}')


def _scan_logs(dir_):
    """Count lock-marker hits across per-task logs and SLURM stderr, with a
    few sample lines."""
    roots = [dir_ / '.remake' / 'tasks' / 'log', dir_ / '.remake' / 'slurm' / 'output']
    hits = []
    for root in roots:
        if not root.is_dir():
            continue
        for path in root.rglob('*'):
            if not path.is_file() or path.suffix not in ('.log', '.err', '.out'):
                continue
            try:
                text = path.read_text(errors='replace')
            except OSError:
                continue
            for line in text.splitlines():
                if any(marker in line for marker in LOCK_MARKERS):
                    hits.append((path.name, line.strip()))
    return hits


def _count_sidecars(dir_):
    root = dir_ / '.remake' / 'tasks' / 'results'
    return sum(1 for _ in root.rglob('*.json')) if root.is_dir() else 0


def cmd_time_ingest(args):
    """Isolate the single-writer ingest cost: fabricate 2*N real sidecars
    (exactly what run-array-task writes) against a fresh DB, then time
    Sqlite3Backend.ingest_sidecars(). No cluster needed; point --dir at the
    same filesystem the real .remake/ DB lives on (e.g. JASMIN scratch) so
    the batched-transaction timing reflects that filesystem."""
    import os
    import time

    from remake.loader import load_remake
    from remake.metadata import TASK_STATUS_SUCCESS
    from remake.metadata.sidecar import SidecarWriter

    dir_ = Path(args.dir)
    dir_.mkdir(parents=True, exist_ok=True)
    params = {'n': args.n, 'work_seconds': 0.0, 'account': args.account,
              'partition': 'standard', 'qos': 'standard',
              'time': '00:20:00', 'mem': '256M'}
    (dir_ / PARAMS_NAME).write_text(yaml.safe_dump(params, sort_keys=False))
    (dir_ / REMAKEFILE_NAME).write_text(REMAKEFILE)

    cwd = os.getcwd()
    os.chdir(dir_)
    try:
        # Fresh DB each run, so we always time a cold ingest into an empty
        # task table (the realistic case: first invocation after a wide run).
        db = Path('.remake/remake.db')
        if db.exists():
            db.unlink()
        rmk = load_remake(REMAKEFILE_NAME, finalize=True)  # real Sqlite3Backend + ensure_rules

        # Write 2*N sidecars exactly as the array elements would.
        writer = SidecarWriter()
        tasks = list(rmk.iter_tasks())
        for task in tasks:
            writer.update_task(task, status=TASK_STATUS_SUCCESS)
        n_sidecars = _count_sidecars(Path('.'))

        t0 = time.perf_counter()
        n_ingested = rmk.metadata.ingest_sidecars(rmk.rules)
        dt = time.perf_counter() - t0
    finally:
        os.chdir(cwd)

    print(f'=== time-ingest ({dir_}) ===')
    print(f'n={args.n}  tasks={len(tasks)}  sidecars written={n_sidecars}')
    print(f'ingested {n_ingested} sidecar(s) in {dt:.3f}s '
          f'({1000 * dt / max(n_ingested, 1):.3f} ms/sidecar)')
    if n_ingested != len(tasks) or _count_sidecars(dir_):
        sys.exit('FAIL: ingest count mismatch or sidecars left behind')


def cmd_report(args):
    dir_ = Path(args.dir)
    params = yaml.safe_load((dir_ / PARAMS_NAME).read_text())
    n = params['n']

    sidecars_before = _count_sidecars(dir_)

    # `remake info` calls plan(), which ingests pending sidecars into the DB
    # before reading it -- this is the single-writer ingest path under test.
    # info emits JSON to stdout (internal output -> JSON is fine).
    result = _remake(dir_, 'info', REMAKEFILE_NAME, '--json')
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        sys.exit(f'`remake info` failed (exit {result.returncode})')
    info = json.loads(result.stdout)
    rules = {r['rule']: r for r in info['rules'] if not r.get('deferred')}

    sidecars_after = _count_sidecars(dir_)
    lock_hits = _scan_logs(dir_)

    print(f'=== bench_slurm_pipeline report ({dir_}) ===')
    print(f'n={n}  work_seconds={params["work_seconds"]}  '
          f'expected {2 * n} tasks (stage1 + stage2)\n')

    ok = True
    print(f'{"rule":<8} {"tasks":>7} {"success":>8} {"failed":>7} {"pending":>8}')
    for name in ('stage1', 'stage2'):
        r = rules.get(name)
        if r is None:
            print(f'{name:<8} (not reported)')
            ok = False
            continue
        print(f'{name:<8} {r["tasks"]:>7} {r["success"]:>8} '
              f'{r["failed"]:>7} {r["pending"]:>8}')
        if r['success'] != n or r['failed'] or r['pending']:
            ok = False

    print(f'\nsidecars before ingest: {sidecars_before}')
    print(f'sidecars after ingest:  {sidecars_after} (expected 0)')
    if sidecars_after:
        ok = False

    print(f'lock-marker lines in logs: {len(lock_hits)} (expected 0)')
    for fname, line in lock_hits[:20]:
        print(f'  {fname}: {line}')

    print()
    if ok and not lock_hits:
        print('PASS: real pipeline path completed with no DB lock contention; '
              'all results ingested.')
    else:
        print('FAIL: see counts above. Re-run `report` if jobs are still in '
              'flight; otherwise investigate failures/lock lines.')
        sys.exit(1)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='cmd', required=True)

    p_setup = sub.add_parser('setup', help='write scratch dir + pipeline')
    p_setup.add_argument('--dir', required=True)
    p_setup.add_argument('--n', type=int, default=800,
                         help='matrix size per rule (2*N tasks total)')
    p_setup.add_argument('--work-seconds', type=float, default=0.0,
                         help='per-task sleep; 0 = max-contention synchronised burst')
    p_setup.add_argument('--account', default=os.environ.get('REMAKE_SLURM_ACCOUNT', 'afesp'))
    p_setup.add_argument('--partition', default='standard')
    p_setup.add_argument('--qos', default='standard')
    p_setup.add_argument('--time', default='00:20:00')
    p_setup.add_argument('--mem', default='256M')
    p_setup.set_defaults(func=cmd_setup)

    p_submit = sub.add_parser('submit', help='submit the pipeline via SLURM')
    p_submit.add_argument('--dir', required=True)
    p_submit.set_defaults(func=cmd_submit)

    p_report = sub.add_parser('report', help='ingest sidecars + check for livelock')
    p_report.add_argument('--dir', required=True)
    p_report.set_defaults(func=cmd_report)

    p_time = sub.add_parser('time-ingest',
                            help='fabricate 2*N sidecars + time ingest_sidecars (no cluster)')
    p_time.add_argument('--dir', required=True)
    p_time.add_argument('--n', type=int, default=800,
                        help='matrix size per rule (2*N sidecars timed)')
    p_time.add_argument('--account', default=os.environ.get('REMAKE_SLURM_ACCOUNT', 'afesp'))
    p_time.set_defaults(func=cmd_time_ingest)

    args = parser.parse_args()
    args.func(args)


if __name__ == '__main__':
    main()
